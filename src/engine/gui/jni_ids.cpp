// hex colour text filter (lower-cases A-F), max 6 chars
extern "C" void hex_colour_text_filter(char *buf, char character) {
    unsigned long long n = libc_strlen(buf);
    if (n > 5) return;
    if ((unsigned char)(character - 0x41) <= 5) {
        character |= 0x20;
    } else {
        unsigned char l = (unsigned char)(character - 0x61);

        unsigned char nl = l >= 6;

        unsigned char d = (unsigned char)(character - 0x30);

        unsigned char nd = d >= 10;

        if (nl & nd) return;
    }
    buf[n] = character;
}

